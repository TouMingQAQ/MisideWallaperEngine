const DICTS: Record<Language, Record<I18nKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

let current: Language = "zh-CN";
const listeners = new Set<() => void>();

export function getLang(): Language {
  return current;
}

/** 由 store 在设置变化时调用 */
export function setLang(lang: Language): void {
  if (lang === current) return;
  current = lang;
  document.documentElement.lang = lang;
  for (const fn of listeners) {
    try {
      fn();
    } catch (err) {
      console.error("[wp] i18n listener failed", err);
    }
  }
}

/** 订阅语言切换（只在需要重刷静态外壳文案时用） */
export function onLangChange(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export type TParams = Record<string, string | number> | Array<string | number>;

/**
 * 取词。缺失 key 时回退到中文，再回退到 key 本身（绝不抛错）。
 * 模板里的 {0} / {name} 会被 params 替换。
 */
export function t(key: I18nKey, params?: TParams): string {
  const dict = DICTS[current] ?? zhCN;
  let text: string = dict[key] ?? zhCN[key] ?? String(key);
  if (params === undefined) return text;

  if (Array.isArray(params)) {
    text = text.replace(/\{(\d+)\}/g, (match, idx: string) => {
      const v = params[Number(idx)];
      return v === undefined ? match : String(v);
    });
    return text;
  }
  text = text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const v = params[name];
    return v === undefined ? match : String(v);
  });
  return text;
}

/** 给 store 的「后端未就绪」提示用：按当前语言取一条文案 */
export function tBackendUnavailable(): string {
  return `${t("backend.unavailable")} — ${t("backend.unavailableHint")}`;
}
